#pragma once

#include <string>

enum class TOKEN_SET{
    TOKEN_CREATE,
    TOKEN_DB,
    TOKEN_TABLE,

    TOKEN_INSERT,
    TOKEN_IN,
    TOKEN_VALUES,

    TOKEN_TYPE_INT,
    TOKEN_TYPE_VARCHAR,

    TOKEN_CONSTRAINT_PRIMARYKEY,
    TOKEN_CONSTRAINT_UNIQUE,

    TOKEN_STRING_VALUE,
    TOKEN_INT_VALUE,

    TOKEN_LEFT_PARENTHESES,
    TOKEN_RIGHT_PARENTHESES,
    TOKEN_LEFTSQBRACKET,
    TOKEN_RIGHTSQBRACKET,
    TOKEN_COMMA
};

struct TOKEN{
    TOKEN_SET tokenType;
    std::string value;
};
